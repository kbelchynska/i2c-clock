#pragma once
#include <Arduino.h>

// Шрифт 5×7: лише символи, потрібні для годинника.
// Кожен символ — 5 колонок, біт 0 = верхній піксель (як у GDDRAM SSD1306).
namespace font
{

    constexpr int CHAR_W = 5;
    constexpr int CHAR_H = 7;

    struct Glyph
    {
        char c;
        uint8_t cols[CHAR_W];
    };

    static const Glyph GLYPHS[] = {
        {' ', {0x00, 0x00, 0x00, 0x00, 0x00}},
        {'-', {0x08, 0x08, 0x08, 0x08, 0x08}},
        {'.', {0x00, 0x60, 0x60, 0x00, 0x00}},
        {':', {0x00, 0x36, 0x36, 0x00, 0x00}},
        {'0', {0x3E, 0x51, 0x49, 0x45, 0x3E}},
        {'1', {0x00, 0x42, 0x7F, 0x40, 0x00}},
        {'2', {0x42, 0x61, 0x51, 0x49, 0x46}},
        {'3', {0x21, 0x41, 0x45, 0x4B, 0x31}},
        {'4', {0x18, 0x14, 0x12, 0x7F, 0x10}},
        {'5', {0x27, 0x45, 0x45, 0x45, 0x39}},
        {'6', {0x3C, 0x4A, 0x49, 0x49, 0x30}},
        {'7', {0x01, 0x71, 0x09, 0x05, 0x03}},
        {'8', {0x36, 0x49, 0x49, 0x49, 0x36}},
        {'9', {0x06, 0x49, 0x49, 0x29, 0x1E}},
        {'F', {0x7F, 0x09, 0x09, 0x01, 0x01}},
        {'M', {0x7F, 0x02, 0x0C, 0x02, 0x7F}},
        {'S', {0x46, 0x49, 0x49, 0x49, 0x31}},
        {'T', {0x01, 0x01, 0x7F, 0x01, 0x01}},
        {'W', {0x3F, 0x40, 0x38, 0x40, 0x3F}},
        {'a', {0x20, 0x54, 0x54, 0x54, 0x78}},
        {'d', {0x38, 0x44, 0x44, 0x48, 0x7F}},
        {'e', {0x38, 0x54, 0x54, 0x54, 0x18}},
        {'h', {0x7F, 0x08, 0x04, 0x04, 0x78}},
        {'i', {0x00, 0x44, 0x7D, 0x40, 0x00}},
        {'n', {0x7C, 0x08, 0x04, 0x04, 0x78}},
        {'o', {0x38, 0x44, 0x44, 0x44, 0x38}},
        {'r', {0x7C, 0x08, 0x04, 0x04, 0x08}},
        {'t', {0x04, 0x3F, 0x44, 0x40, 0x20}},
        {'u', {0x3C, 0x40, 0x40, 0x20, 0x7C}},
    };

    // Невідомий символ малюється як пробіл
    inline const uint8_t *glyph(char c)
    {
        for (const Glyph &g : GLYPHS)
            if (g.c == c)
                return g.cols;
        return GLYPHS[0].cols;
    }

} // namespace font
